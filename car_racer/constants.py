# калибровка длины). Привязана СПЕЦИАЛЬНО к спрайту тренировочной машины
# (`PhyCar(..., car_size=(15, 35), ...)` в neat_runner/game_instatnse.py,
# 15x35 px), а не к какому-то независимому измерению - пользователь попросил
# считать иконку машины реальной машиной/картом. 15px ширины -> 0.75 м,
# 35px длины -> 1.75 м - правдоподобные габариты прокатного картинга (см. уже
# существующую формулировку "типичный прокатный картинг" у ENGINE_POWER_HP).
# Отсюда PX_PER_METER = 15 / 0.75 = 35 / 1.75 = 20.0 (оба измерения сходятся
# на одном множителе - не совпадение, а то, как подбирались 0.75/1.75).
#
# Используется ТОЛЬКО для геометрии/визуализации (масштаб трасс при
# генерации/импорте, масштабная линейка на экране, см. Screen.draw_scale_bar) -
# НЕ трогает физику/скорость/сцепление машины (MAX_SPEED, GRIP_ACCEL,
# ENGINE_POWER_HP, ROTATE_POWER и т.п. в physic_car.py остаются в своих
# игровых единицах px/с, px/с^2, как и были - см. комментарии там же про то,
# что это отдельная, уже подобранная под ощущение вождения калибровка,
# трогать которую эта задача не должна).
